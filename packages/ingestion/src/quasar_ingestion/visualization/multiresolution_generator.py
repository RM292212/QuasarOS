"""
Deterministic Multiresolution Volume Generator & Brick Extractor (TASK-04B).

Extracts and builds multiresolution 3D volume pyramids and sub-volume bricks from canonical
Zarr stores for WebGPU / WebGL2 scientific ocean volume rendering according to approved
TASK-04A specifications:
- Brick Shape: (64, 64, 32) [lon, lat, depth]
- Boundary Halo: (1, 1, 0) [lon, lat, depth] -> Allocated Shape (66, 66, 32)
- Hierarchy: Strategy 3 (Horizontal 2x2 downsampling, vertical 31 levels preserved with 1D Depth LUT)
  - LOD 0: (97, 181, 31) -> (2, 3, 1) = 6 bricks / timestep
  - LOD 1: (49, 91, 31) -> (1, 2, 1) = 2 bricks / timestep
  - LOD 2: (25, 46, 31) -> (1, 1, 1) = 1 brick / timestep
- Precision: Float16 primary ('r16float') + Linear Uint16 fallback with reserved missing code 65535.
- Downsampling rule: Mask-preserving arithmetic mean of valid sub-voxels.
- Determinism: Bitwise reproducible outputs, deterministic manifests, SHA-256 integrity verification.
"""

